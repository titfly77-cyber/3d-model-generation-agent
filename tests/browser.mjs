import { chromium } from '../frontend/node_modules/playwright/index.mjs';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
for (const name of ['TEMP', 'TMP', 'TMPDIR']) process.env[name]=path.join(root,'tmp');
const out=path.join(root,'data','verification');fs.mkdirSync(out,{recursive:true});
const profile=fs.mkdtempSync(path.join(root,'cache','browser-test-'));
const browser=await chromium.launchPersistentContext(profile,{executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,viewport:{width:1600,height:1000},deviceScaleFactor:1,acceptDownloads:true,downloadsPath:path.join(root,'tmp'),args:['--no-first-run','--disable-extensions','--disable-background-networking','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
process.on('uncaughtException',async error=>{console.error(error);await browser.close();process.exit(1);});
const page=await browser.newPage();const errors=[];
page.on('pageerror',error=>errors.push(error.message));
page.on('console',message=>{if(message.type()==='error'&&!message.text().includes('favicon.ico'))errors.push(message.text());});
await page.goto('http://127.0.0.1:8765',{waitUntil:'networkidle'});
try { await page.locator('.model-caption').waitFor({timeout:30000}); }
catch(error){await page.screenshot({path:path.join(out,'failure.png'),fullPage:true});console.log('PAGE ERRORS',JSON.stringify(errors));console.log('BODY',await page.locator('body').innerText());await browser.close();throw error;}
await page.waitForFunction(()=>document.querySelector('canvas')?.width>0);
await page.waitForTimeout(5000);
await page.screenshot({path:path.join(out,'studio-desktop.png'),fullPage:true});
await page.getByRole('button',{name:'线框',exact:true}).click();
await page.getByRole('button',{name:'自动旋转',exact:true}).click();
await page.getByRole('button',{name:'重置视角',exact:true}).click();
await page.getByRole('button',{name:'自动旋转',exact:true}).click();
await page.getByRole('button',{name:'线框',exact:true}).click();
await page.getByRole('button',{name:'模型设置',exact:true}).click();
await page.getByRole('dialog').waitFor();
await page.getByRole('textbox',{name:'文生图模型 ID',exact:true}).waitFor();
if(!(await page.getByRole('textbox',{name:'文生图模型 ID',exact:true}).inputValue()))throw new Error('Image model settings did not load');
for(const field of await page.locator('input[type=password]').all())if(await field.inputValue())throw new Error('Saved API keys must not be echoed');
await page.screenshot({path:path.join(out,'settings.png')});
await page.getByRole('button',{name:'关闭设置',exact:true}).click();
if(await page.getByRole('button',{name:'继续修改这个设计'}).count())throw new Error('Legacy editing should not be offered for new neural workflow');
const downloadPromise=page.waitForEvent('download',{timeout:60000});
await page.evaluate(()=>{const original=URL.createObjectURL;URL.createObjectURL=function(blob){window.downloadBlobSize=blob.size;return original.call(URL,blob);};});
await page.getByRole('link',{name:'下载资产包'}).click();
const download=await downloadPromise;
await download.saveAs(path.join(out,'download-test.zip'));
console.log('Download diagnostics',JSON.stringify({blobSize:await page.evaluate(()=>window.downloadBlobSize),failure:await download.failure(),path:await download.path(),savedBytes:fs.statSync(path.join(out,'download-test.zip')).size}));
if(fs.statSync(path.join(out,'download-test.zip')).size<1000)throw new Error('Downloaded asset archive is empty');
await page.getByRole('button',{name:/资产库/}).click();
await page.locator('.library-grid .asset-card').first().waitFor();
await page.screenshot({path:path.join(out,'asset-library.png')});
await page.getByRole('textbox',{name:'搜索资产'}).fill('ORBIT');
if(await page.locator('.library-grid .asset-card').count()!==1)throw Error('Search filtering failed');
await page.locator('.library-grid .asset-card').first().click();
await page.waitForTimeout(1500);
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:path.join(out,'studio-mobile.png'),fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth+1);
await browser.close();
fs.writeFileSync(path.join(out,'browser-result.json'),JSON.stringify({mode:'live-local-existing-assets-no-generation',errors,mobileOverflow:overflow,downloadBytes:fs.statSync(path.join(out,'download-test.zip')).size,checked:['desktop viewport','GLB load','wireframe','autorotate','settings','legacy edit removed','ZIP download','library','search','mobile']},null,2));
console.log(JSON.stringify({errors,mobileOverflow:overflow}));
if(errors.length||overflow)process.exit(1);
